/**
 * Generates `src/lib/world-countries.generated.ts` (stylized equirectangular
 * SVG paths per ISO-3166 alpha-2 country) from `world-atlas` 110m data.
 * Dev-time only — runtime has no topojson / d3 dependency.
 *
 *   pnpm --filter @starboard/ext-geo-gazetteer build:map
 */
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

import countries from "i18n-iso-countries"
import { feature } from "topojson-client"

const require = createRequire(import.meta.url)
const topology = JSON.parse(
  readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8")
)

const WIDTH = 1000
const LAT_TOP = 84
const LAT_BOTTOM = -58
const HEIGHT = Math.round(((LAT_TOP - LAT_BOTTOM) / 360) * WIDTH)

const px = (lng) => ((lng + 180) / 360) * WIDTH
const py = (lat) => ((LAT_TOP - lat) / 360) * WIDTH
const round = (n) => Math.round(n * 10) / 10

function ringArea(ring) {
  let area = 0
  for (let i = 0; i < ring.length - 1; i++) {
    area += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1]
  }
  return area / 2
}

function ringCentroid(ring) {
  let cx = 0
  let cy = 0
  let a = 0
  for (let i = 0; i < ring.length - 1; i++) {
    const f = ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1]
    cx += (ring[i][0] + ring[i + 1][0]) * f
    cy += (ring[i][1] + ring[i + 1][1]) * f
    a += f
  }
  if (a === 0) return ring[0]
  return [cx / (3 * a), cy / (3 * a)]
}

function ringPath(ring) {
  const pts = []
  let last = ""
  for (const [lng, lat] of ring) {
    const x = round(px(lng))
    const y = round(py(lat))
    const key = `${x},${y}`
    if (key === last) continue
    last = key
    pts.push(key)
  }
  if (pts.length < 3) return ""
  return `M${pts.join("L")}Z`
}

const out = []
for (const f of feature(topology, topology.objects.countries).features) {
  const iso2 = countries.numericToAlpha2(String(f.id).padStart(3, "0"))
  if (!iso2 || iso2 === "AQ") continue
  const polygons =
    f.geometry.type === "Polygon"
      ? [f.geometry.coordinates]
      : f.geometry.coordinates
  const rings = polygons.map((p) => p[0])
  const largest = rings.reduce((a, b) =>
    Math.abs(ringArea(a)) >= Math.abs(ringArea(b)) ? a : b
  )
  const [lng, lat] = ringCentroid(largest)
  const xs = largest.map(([x]) => px(x))
  const ys = largest.map(([, y]) => py(y))
  const box = [
    round(Math.min(...xs)),
    round(Math.min(...ys)),
    round(Math.max(...xs)),
    round(Math.max(...ys)),
  ]
  const d = rings.map(ringPath).join("")
  if (!d) continue
  out.push({
    id: iso2,
    name: f.properties.name,
    d,
    lng: round(lng),
    lat: round(lat),
    box,
  })
}
out.sort((a, b) => a.id.localeCompare(b.id))

const body = `// AUTO-GENERATED by scripts/build-world-map.mjs — do not edit.
// Source: world-atlas countries-110m (Natural Earth, public domain).

export type WorldCountryShape = {
  /** ISO-3166 alpha-2. */
  id: string
  name: string
  /** SVG path in the equirectangular viewBox below. */
  d: string
  /** Label / curve anchor (largest landmass centroid). */
  lng: number
  lat: number
  /** Largest-landmass bounds in viewBox units: [x0, y0, x1, y1]. */
  box: readonly [number, number, number, number]
}

export const WORLD_WIDTH = ${WIDTH}
export const WORLD_HEIGHT = ${HEIGHT}
export const WORLD_LAT_TOP = ${LAT_TOP}

export const WORLD_COUNTRIES: readonly WorldCountryShape[] = ${JSON.stringify(out)}
`
writeFileSync(
  new URL("../src/lib/world-countries.generated.ts", import.meta.url),
  body
)
console.log(
  `wrote ${out.length} countries, ${(body.length / 1024).toFixed(0)} KB`
)
